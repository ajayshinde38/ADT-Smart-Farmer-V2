const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const source=fs.readFileSync('src/utils/fertilizerPresentation.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const context={exports:{}};vm.runInNewContext(compiled,context);
const {fertilizerName,fertilizerUnit,doseProducts}=context.exports;
assert.equal(fertilizerName('Ammonium Sulphate','mr'),'अमोनियम सल्फेट');
assert.equal(fertilizerName('Muriate of Potash','mr'),'म्युरिएट ऑफ पोटॅश');
assert.equal(fertilizerName('Humic + Fulvic Acid','mr'),'ह्युमिक + फुल्विक आम्ल');
assert.equal(fertilizerName('09:24:24','mr'),'09:24:24');
assert.equal(fertilizerName('Calcium Nitrate: 3 kg','en'),'Calcium Nitrate: 3 kg');
assert.equal(fertilizerName('UREA: 25 kg','mr'),'युरिया: 25 kg');
assert.equal(fertilizerName('Unknown product','mr'),'Unknown product');
assert.equal(fertilizerUnit('kg','mr'),'किलो');
const dose={products:[{fertilizer:'Urea',quantity:0,unit:'kg',water_liters:100}],recommendation_text:''};
const original=JSON.stringify(dose);
const [row]=doseProducts(dose,'mr');
assert.equal(row.name,'युरिया');assert.equal(row.quantity,'0 किलो');assert.equal(row.water,'पाणी: 100 लिटर');
assert.equal(JSON.stringify(dose),original,'Display translation must not mutate saved product identifiers or quantities');
assert.equal(doseProducts({products:[],recommendation_text:'Urea: 5 kg\n'},'mr')[0].name,'युरिया: 5 kg');
console.log('Fertilizer display checks passed: Marathi names, grade preservation, zero quantities, water details, English and immutable source data.');
